import streamlit as st

st.set_page_config(page_title="Sobre o Projeto", layout="centered")

st.title("📘 Sobre o Projeto")

st.markdown("""
Este projeto foi desenvolvido como parte de um projeto integrador com o objetivo de facilitar a tomada de decisão de investidores iniciantes em criptomoedas.

### 🎯 Objetivos
- Utilizar dados históricos da CoinGecko
- Aplicar estatística preditiva e aprendizado de máquina
- Criar uma interface visual interativa com Streamlit

### 📊 Resultados até agora
- Coleta e análise descritiva dos dados
- Visualização interativa com gráficos
- Implementação de modelo preditivo simples

### 💡 Motivação
A dificuldade de interpretação de dados por investidores iniciantes pode levar a decisões impulsivas. Este projeto busca reduzir essa incerteza por meio de uma ferramenta acessível, visual e inteligente.
""")
